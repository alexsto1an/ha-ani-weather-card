// Assembles the live demo in _site/: the page, the card bundle and the note
// writer's (built by `npm run build` first) and the icons the cards use,
// taken from @mdi/js so the page doesn't download all 7,000 of them.
//
//   npm run demo     → _site/, ready to serve or publish to GitHub Pages

import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as mdi from '@mdi/js';
import { logoSvg } from './logo.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

/** The pages' own files, copied as they are: the live demo, and the setup guide in setup/. */
export const PAGE_FILES = [
    'index.html', 'demo.css', 'demo.js', 'scene.mjs', 'code.mjs', 'clock.js', 'ha-elements.js',
    'setup/index.html', 'setup.css', 'setup.js',
];
/** The pages: each loads GSAP from the card's own URL and wears the mark in its top bar. */
const PAGES = ['index.html', 'setup/index.html'];

/** The tracker builds these names at runtime from the moon sensor's state. */
export const MOON_ICONS = [
    'new', 'waxing-crescent', 'first-quarter', 'waxing-gibbous',
    'full', 'waning-gibbous', 'last-quarter', 'waning-crescent',
].map(phase => `mdi:moon-${phase}`);

const sourceFiles = (dir, pattern) => readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? sourceFiles(path, pattern) : pattern.test(path) ? [path] : [];
});

/** Every mdi: icon the cards name in their source, the page's own icons, and the moon phases. */
export function iconNames(srcDir = join(root, 'src'), demoDir = here) {
    const names = new Set(MOON_ICONS);
    const files = [...sourceFiles(srcDir, /\.ts$/), ...sourceFiles(demoDir, /\.(m?js|html)$/)];
    for (const file of files) {
        for (const [name] of readFileSync(file, 'utf8').matchAll(/mdi:[a-z0-9-]+/g)) {
            // `mdi:moon-${…}` leaves a bare prefix behind; the phases are above
            if (!name.endsWith('-')) names.add(name);
        }
    }
    return [...names].sort();
}

const exportName = (icon) => 'mdi' + icon.slice(4).split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('');

/** Icon name → SVG path. Throws if a name doesn't exist in @mdi/js, so a typo can't ship as a blank icon. */
export function resolveIcons(names = iconNames()) {
    const missing = names.filter(name => typeof mdi[exportName(name)] !== 'string');
    if (missing.length) throw new Error(`No @mdi/js icon for: ${missing.join(', ')}`);
    return Object.fromEntries(names.map(name => [name, mdi[exportName(name)]]));
}

export function build(out = join(root, '_site')) {
    rmSync(out, { recursive: true, force: true });
    mkdirSync(out, { recursive: true });
    for (const file of PAGE_FILES) {
        mkdirSync(dirname(join(out, file)), { recursive: true });
        copyFileSync(join(here, file), join(out, file));
    }
    // The pages load GSAP themselves, from the card's own URL (see index.html), and get the mark,
    // drawn into the markup so it's there on the first paint
    const gsapUrl = readFileSync(join(root, 'src/constants.ts'), 'utf8').match(/GSAP_CDN_URL = '([^']+)'/)?.[1];
    if (!gsapUrl) throw new Error('GSAP_CDN_URL not found in src/constants.ts');
    const mark = logoSvg({ className: 'wordmark-glyph logo-mark' });
    for (const file of PAGES) {
        const page = join(out, file);
        writeFileSync(page, readFileSync(page, 'utf8').replace('%GSAP_CDN_URL%', gsapUrl).replace('%LOGO%', mark));
    }
    // The favicon: the mark by day, standing alone (browsers don't animate favicons)
    writeFileSync(join(out, 'favicon.svg'), logoSvg({ only: 'day', id: 'favicon' }));
    copyFileSync(join(root, 'animated-weather-card.js'), join(out, 'animated-weather-card.js'));
    copyFileSync(join(root, 'animated-weather-card-note.js'), join(out, 'animated-weather-card-note.js'));
    copyFileSync(join(root, 'animated-weather-card-planes.js'), join(out, 'animated-weather-card-planes.js'));
    const icons = resolveIcons();
    writeFileSync(join(out, 'icons.js'), `// Generated by demo/build.mjs from @mdi/js\nwindow.AWC_DEMO_ICONS = ${JSON.stringify(icons)};\n`);
    return { out, icons: Object.keys(icons).length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const { out, icons } = build();
    console.log(`Demo assembled in ${out} (${icons} icons)`);
}
