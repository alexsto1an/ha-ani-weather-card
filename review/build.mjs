// Assembles the forecast and clock review page in _review/: the page, the
// card's bundles, the demo's sample world and stand-ins, and the icons the
// cards and the page name. Review only: this folder goes once the variants
// are picked.
//
//   npm run build && node review/build.mjs   → _review/, serve it or publish it

import { copyFileSync, mkdirSync, rmSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { iconNames, resolveIcons } from '../demo/build.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, '_review');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const file of ['index.html', 'review.css', 'review.js', 'forecast-sample.mjs']) copyFileSync(join(here, file), join(out, file));
for (const file of ['scene.mjs', 'clock.js', 'ha-elements.js']) copyFileSync(join(root, 'demo', file), join(out, file));
const bundles = readdirSync(root).filter(name => /^animated-weather-card.*\.js$/.test(name));
for (const bundle of bundles) copyFileSync(join(root, bundle), join(out, bundle));
// The demo's icons, and any the review page names
const names = [...new Set([...iconNames(), ...iconNames(join(root, 'src'), here)])].sort();
const icons = resolveIcons(names);
writeFileSync(join(out, 'icons.js'), `// Generated by review/build.mjs from @mdi/js\nwindow.AWC_DEMO_ICONS = ${JSON.stringify(icons)};\n`);
console.log(`Review assembled in ${out}: ${bundles.length} bundles, ${Object.keys(icons).length} icons`);
